def apply_grade9_more(grades, rich_lesson):
    by_slug = {s["slug"]: s for s in grades[9]}
    for slug, items in MORE.items():
        subject = by_slug[slug]
        known = {l["title"] for l in subject["lessons"]}
        subject["lessons"].extend(_build(slug, it, rich_lesson) for it in items if it[0] not in known)
