import hashlib

def _build(subject, item, rich_lesson):
    title, explain, rule, example, task, question, right, w1, w2, mistake = item
    # Розташування правильної відповіді залежить від назви (стабільно між запусками).
    pos = int(hashlib.md5(title.encode("utf-8")).hexdigest(), 16) % 3
    options = [w1, w2]
    options.insert(pos, right)
    extra = f"Склади власне завдання за темою «{title}», розв’яжи його та поясни кожен крок."
    return rich_lesson(title, explain, rule, example, task, question, options, pos,
                       list(STEPS[subject]), mistake, extra)


