def apply_grade9_books(grades, rich_lesson):
    """Додає уроки за орієнтирами підручників у кінець предметів 9 класу."""
    subjects = grades[9]
    by_slug = {s["slug"]: s for s in subjects}
    if "law" not in by_slug:
        law = {**LAW_SUBJECT, "lessons": []}
        position = next((i + 1 for i, s in enumerate(subjects) if s["slug"] == "civics"), len(subjects))
        subjects.insert(position, law)
        by_slug["law"] = law
    for slug, items in NEW_LESSONS.items():
        subject = by_slug[slug]
        known = {l["title"] for l in subject["lessons"]}
        subject["lessons"].extend(rich_lesson(*item) for item in items if item[0] not in known)
        subject["reference_book"] = BOOKS[slug]
